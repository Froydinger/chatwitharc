// Real, disposable local Postgres; no production database, credentials or providers.
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { spawnSync, spawn } from 'node:child_process';
const dir=mkdtempSync(join(tmpdir(),'arc-image-credits-'));
const data=join(dir,'data');
const run=(cmd,args)=>{const result=spawnSync(cmd,args,{encoding:'utf8'});if(result.status)throw Error(result.stderr || result.stdout);return result.stdout;};
const args=['-h',dir,'-p','54389','-d','postgres','-X','-v','ON_ERROR_STOP=1','-At'];
const sql=query=>run('psql',[...args,'-c',query]);
const queryAsync=query=>new Promise((resolve,reject)=>{const p=spawn('psql',[...args,'-c',query]);let out='',err='';p.stdout.on('data',v=>out+=v);p.stderr.on('data',v=>err+=v);p.on('error',reject);p.on('close',status=>status?reject(Error(err)):resolve(out));});
const parse=out=>JSON.parse(out.trim().split('\n').at(-1));
const free=randomUUID(),other=randomUUID(),boost=randomUUID();
const reserve=(id,key,count=1)=>`SET ROLE service_role; SET request.jwt.claim.role='service_role'; SELECT public.reserve_arc_image_credits('${id}','${key}',${count});`;
const finalize=(key,count)=>sql(`SET ROLE service_role; SET request.jwt.claim.role='service_role'; SELECT public.finalize_arc_image_credits('${key}',${count});`);
const used=(id,date='current_date')=>Number(sql(`SELECT used_credits FROM arc_image_credit_usage WHERE user_id='${id}' AND usage_date=${date};`).trim());
const job=(owner,model)=>{const id=randomUUID();sql(`INSERT INTO image_generation_jobs VALUES('${id}','${owner}','${model}');`);return id;};
let started=false;
try {
 run('initdb',['-D',data,'--auth=trust','--no-locale']);
 run('pg_ctl',['-D',data,'-l',join(dir,'postgres.log'),'-o',`-k ${dir} -h '' -p 54389`,'-w','start']); started=true;
 sql(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
 CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY, boost boolean NOT NULL DEFAULT false);
 CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql AS $$ SELECT current_setting('request.jwt.claim.role',true) $$;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 GRANT USAGE ON SCHEMA auth TO authenticated,service_role;
 CREATE FUNCTION public.user_has_boost(check_user_id uuid) RETURNS boolean LANGUAGE sql SECURITY DEFINER AS $$ SELECT boost FROM auth.users WHERE id=check_user_id $$;
 INSERT INTO auth.users VALUES('${free}',false),('${other}',false),('${boost}',true);`);
 sql('CREATE TABLE public.image_generation_jobs(id uuid PRIMARY KEY,user_id uuid REFERENCES auth.users(id),preferred_model text);');
 const migration=readFileSync('supabase/migrations/20260930071352_arc_daily_image_credits.sql','utf8');
 sql(migration);
 const cheap=job(free,'gpt-image-2.5-flare'),nano=job(free,'gemini-3.1-flash-image');
 assert.equal(parse(sql(reserve(free,cheap,3))).used,3);
 assert.equal(parse(sql(reserve(free,nano,2))).used,7);
 assert.equal(parse(sql(reserve(free,job(free,'gpt-image-2.5-sunburst')))).used,8);
 assert.equal(parse(sql(reserve(free,job(free,'gemini-3.1-flash-image')))).allowed,false,'Models share one allowance');
 assert.throws(()=>sql(reserve(free,cheap)),/already reserved/);
 assert.throws(()=>sql(reserve(other,cheap)),/Invalid image job/);
 assert.throws(()=>sql(reserve(free,job(free,'forged-model'))),/Unsupported/);
 finalize(cheap,1); assert.equal(used(free),6,'Partial cheap batch refunds failed outputs');
 finalize(nano,1); assert.equal(used(free),4,'Partial Nano batch refunds two credits per failed output');
 finalize(nano,0); assert.equal(used(free),4,'Finalize replay cannot refund twice');
 const pending=Array.from({length:16},()=>job(free,'gpt-image-2.5-flare'));
 const results=await Promise.all(pending.map(key=>queryAsync(reserve(free,key))));
 assert.equal(results.filter(out=>parse(out).allowed).length,4,'Concurrent calls cannot overspend credits');
 assert.equal(used(free),8);
 const successfulKeys=pending.filter((_,i)=>parse(results[i]).allowed);
 assert.throws(()=>finalize(successfulKeys[0],2),/Invalid successful/);
 sql(migration); assert.equal(used(free),8,'Migration replay preserves reservations and usage');
 const boostJob=job(boost,'gemini-3.1-flash-image');
 const boostResult=parse(sql(reserve(boost,boostJob,3)));
 assert.equal(boostResult.remaining,null); assert.equal(boostResult.isBoost,true);
 assert.equal(used(boost),0); finalize(boostJob,0); assert.equal(used(boost),0);
 const otherJob=job(other,'gpt-image-2.5-flare');sql(reserve(other,otherJob));
 assert.equal(parse(sql(`SET ROLE authenticated; SET request.jwt.claim.sub='${other}'; SELECT get_my_arc_image_credits();`)).used,1,'Getter is account scoped');
 assert.throws(()=>sql('SET ROLE authenticated; SELECT * FROM arc_image_credit_usage;'),/permission denied/);
 assert.throws(()=>sql(`SET ROLE authenticated; SELECT reserve_arc_image_credits('${other}','${otherJob}',1);`),/permission denied/);
 assert.throws(()=>sql('SET ROLE anon; SELECT get_my_arc_image_credits();'),/permission denied/);
 sql(`UPDATE arc_image_credit_usage SET usage_date=usage_date-1 WHERE user_id='${free}'; UPDATE arc_image_credit_reservations SET usage_date=usage_date-1 WHERE user_id='${free}';`);
 sql(reserve(free,job(free,'gemini-3.1-flash-image')));
 assert.equal(used(free),2,'UTC rollover creates a fresh allowance');
 finalize(successfulKeys[0],0); assert.equal(used(free),2,'Late refund does not change new-day credits');
 assert.equal(used(free,'current_date-1'),7,'Late failure refunds its original reservation day');
 console.log('Real Postgres image credits passed: mixed models, partial/refailed refunds, batches, concurrent cap, Boost, access grants, owner checks, UTC rollover and migration replay.');
} finally {
 if(started)run('pg_ctl',['-D',data,'-m','immediate','-w','stop']);
 rmSync(dir,{recursive:true,force:true});
}
