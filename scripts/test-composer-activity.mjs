import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const exports = {};
new Function('exports', ts.transpileModule(readFileSync('src/lib/chat-input/activity.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(exports);
const {createComposerActivity} = exports;
const calls=[];
let activeId=null, cancelled=false, controllerClears=0;
const store=Object.fromEntries(['setLoading','setGeneratingImage','setSearchingChats','setAccessingMemory','setSearchingWeb','setActiveTask','setActiveStatusDetails'].map(name=>[name,value=>calls.push([name,value])]));
const create=work=>createComposerActivity({work,store:()=>store,getActiveId:()=>activeId,setActiveId:value=>{activeId=value;},getCancelled:()=>cancelled,setCancelled:value=>{cancelled=value;},clearController:()=>{controllerClears++;}});
const rejected=create(false);rejected.finish(false);
assert.equal(calls.length,0,'Rejected work never owns cleanup');
const old=create(false);old.setLoading(true);old.setSearchingWeb(true);
const current=create(false);current.setLoading(true);const currentId=activeId;const count=calls.length;
old.setLoading(false);old.setSearchingWeb(false);old.finish(false);
assert.equal(calls.length,count,'Late old result cannot clear newer activity');
assert.equal(activeId,currentId);assert.equal(controllerClears,0);
current.finish(false);const completedCount=calls.length;current.finish(false);
assert.equal(calls.length,completedCount,'Terminal cleanup runs once');
assert.equal(activeId,null);assert.equal(controllerClears,1);
assert.ok(calls.some(([name,value])=>name==='setLoading'&&value===false));
const stopped=create(false);stopped.setLoading(true);activeId=null;cancelled=true;
const stoppedCount=calls.length;stopped.finish(false);
assert.equal(calls.length,stoppedCount,'Cancelled attempt leaves Stop/new owner cleanup intact');
assert.equal(controllerClears,1);
const work=create(true);work.setLoading(true);const handoffStart=calls.length;work.finish(true);
assert.ok(!calls.slice(handoffStart).some(([name])=>name==='setLoading'),'Durable handoff retains its loading projection');
assert.equal(controllerClears,2);work.finish(true);assert.equal(controllerClears,2);
const completedWork=create(true);completedWork.setLoading(true);completedWork.finish(false);
assert.deepEqual(calls.filter(([name])=>name==='setLoading').at(-1),['setLoading',false]);
console.log('Activity lifetime checks passed: rejected, stale, completed once, Stop cancellation and durable Work handoff/completion.');
