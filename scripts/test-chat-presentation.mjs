import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const code = ts.transpileModule(readFileSync('src/lib/chatPresentation.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exported={};new Function('exports',code)(exported);
const {shouldShowSearchCard,hasSessionCloudProgress}=exported;
const text={role:'assistant',type:'text'};
assert.equal(shouldShowSearchCard(text),false);
assert.equal(shouldShowSearchCard({...text,webSources:[{url:'https://example.com'}]}),true);
assert.equal(shouldShowSearchCard({...text,memoryAction:{type:'web_searched',query:'coffee nearby'}}),true);
assert.equal(shouldShowSearchCard({...text,voiceSearchResult:true}),true);
assert.equal(shouldShowSearchCard({...text,role:'user',webSources:[{url:'https://example.com'}]}),false);
assert.equal(shouldShowSearchCard({...text,type:'canvas',webSources:[{url:'https://example.com'}]}),false);
for(const status of ['queued','running','awaiting_input']) assert.equal(hasSessionCloudProgress([{sessionId:'a',run:{status}}],'a'),true);
for(const status of ['completed','failed','cancelled']) assert.equal(hasSessionCloudProgress([{sessionId:'a',run:{status}}],'a'),false);
assert.equal(hasSessionCloudProgress([{sessionId:'a'}],'a'),true);
assert.equal(hasSessionCloudProgress([{sessionId:'b',run:{status:'running'}}],'a'),false);
assert.equal(hasSessionCloudProgress([{sessionId:null}],null),false);
console.log('Search presentation and session-scoped cloud progress checks passed.');
