import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import { create } from 'zustand';
const source = readFileSync(new URL('../src/store/useMessageQueueStore.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source.replace("import { create } from 'zustand';", ''), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
new Function('exports', 'create', code)(exports, create);
const store = exports.useMessageQueueStore;
store.getState().addToQueue('first');
store.getState().addToQueue('second');
store.getState().pause();
store.getState().pause();
assert.equal(store.getState().isPaused, true);
assert.equal(store.getState().popNext(), null);
assert.deepEqual(store.getState().queue.map(item => item.content), ['first', 'second']);
store.getState().togglePause();
assert.equal(store.getState().popNext().content, 'first');
assert.equal(store.getState().popNext().content, 'second');
assert.equal(store.getState().popNext(), null);
const input = readFileSync(new URL('../src/components/ChatInput.tsx', import.meta.url), 'utf8');
const cancellation = input.slice(input.indexOf('export const cancelCurrentRequest'), input.indexOf('/**', input.indexOf('export const cancelCurrentRequest')));
assert.ok(cancellation.indexOf('.pause()') < cancellation.indexOf('store.setLoading(false)'));
console.log('Queue Stop regression passed: idempotent pause, retained FIFO, explicit resume, pause before idle.');
